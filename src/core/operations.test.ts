// A full battery can power a sol without making generation sustainable.
const powerGame = createGame("charter", 42);
const world = powerGame.worlds.luna;
for (const tile of world.tiles) tile.building = null;
const modules: BuildingId[] = ["command", "habitat", "habitat", "greenhouse", "greenhouse", ...Array<BuildingId>(6).fill("ice"), ...Array<BuildingId>(4).fill("isru"), ...Array<BuildingId>(4).fill("solar")];
modules.forEach((type, i) => {
  const tile = world.tiles[i];
  tile.terrain = "mare";
  tile.ice = 100;
  tile.building = { type, hp: 100, progress: 0, total: 0 };
});
powerGame.tech.unlocked = ["hydro"];
world.dust = world.radiation = world.shelter = world.quarantine = 0;
world.stock.energy = 100;
world.stock.water = world.stock.regolith = 100;
const targetGame = structuredClone(powerGame);
targetGame.worlds.luna.pop = DIFF.charter.lunaPop;
const currentDraw = forecast(powerGame, "luna").energyDraw;
const targetDraw = forecast(targetGame, "luna").energyDraw;
const solarTiles = world.tiles.filter(t => t.building?.type === "solar");
const generationBetween = (currentDraw + targetDraw) / 2;
for (const tile of solarTiles) tile.building!.hp = (generationBetween - 12) / (11 * solarTiles.length) * 100;
const targetPowerAdvice = operationsBrief(powerGame).population[0];
assert.ok(Object.values(targetPowerAdvice.targetNet).every(n => n >= 0), "Fixture isolates power from consumable deficits");
assert.equal(forecast(powerGame, "luna").brownout, false);
assert.ok(forecast(powerGame, "luna").energyGen > currentDraw);
assert.ok(targetPowerAdvice.targetPower.generation < targetPowerAdvice.targetPower.demand);
assert.match(targetPowerAdvice.next, /before hiring crew/);
for (const tile of solarTiles) tile.building!.hp = (currentDraw - 1 - 12) / (11 * solarTiles.length) * 100;
assert.equal(forecast(powerGame, "luna").brownout, false, "Stored energy masks today's generation deficit");
assert.match(operationsBrief(powerGame).population[0].next, /sustained power.*before expanding/);
console.log("operations: nonmutating goal advice, exact export manifests, deferred sale, return fuel, debt and launch blockers pass");
