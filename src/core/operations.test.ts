import { assert } from "./testAssert";
import { launchShip, previewLaunch, sellCargo } from "./actions";
import { operationsBrief, exportPlan } from "./operations";
import { createGame } from "./state";
import { DIFF, SHIPS } from "./data";
import { forecast } from "./sim";
import type { BuildingId } from "./types";

for (const difficulty of ["survey", "charter", "hardship"] as const) {
  const game = createGame(difficulty, 42);
  const before = JSON.stringify(game);
  const brief = operationsBrief(game);
  assert.equal(JSON.stringify(game), before, "Advice must not alter saves, stock, ships or RNG");
  assert.equal(brief.population[0].target, DIFF[difficulty].lunaPop);
  assert.equal(brief.population[1].target, DIFF[difficulty].marsPop);
  assert.equal(brief.exports[0].ready, false, "No speculative future He3 counted");
  assert.equal(brief.exports[0].sale, 0);
  assert.match(brief.exportNext, /Regolith Sintering/);
  assert.equal(brief.cash.debtFee, 0);
  assert.equal(brief.fleet.target, DIFF[difficulty].ships);
}

// Synthetic stock fixtures test the manifest contract, not campaign balance.
const game = createGame("charter", 42);
const ship = game.ships[0];
game.worlds.luna.stock.he3 = 41.5;
let plan = exportPlan(game, ship.id)!;
assert.ok(plan.ready);
assert.equal(plan.kilograms, SHIPS.courier.cargo);
assert.equal(plan.sale, plan.kilograms * 42);
assert.ok(previewLaunch(game, ship.id, plan.draft).ok);
assert.equal(plan.cashOutlay, 0);
const credits = game.credits;
assert.ok(launchShip(game, ship.id, plan.draft).ok);
assert.equal(game.credits, credits, "An export does not pay until sold at Earth");
assert.equal(exportPlan(game, ship.id), null, "No preparations for in-flight ships");
ship.loc = "earth";
ship.mission = null;
assert.ok(sellCargo(game, ship.id).ok);
assert.equal(game.credits - credits, plan.sale);
game.worlds.luna.stock.he3 = 12;
ship.fuel = 0;
plan = exportPlan(game, ship.id)!;
assert.ok(plan.ready);
assert.equal(plan.draft.fuel, plan.fuelBurn, "Earth preparation covers both legs, not only outbound");
assert.equal(plan.saleSol, game.turn + 2);
assert.equal(plan.cashOutlay, previewLaunch(game, ship.id, plan.draft).cost);
assert.ok(plan.cashOutlay > 0);
assert.equal(plan.legRisks.length, 2);
const founder = { ...ship, id: "founder", cls: "colony" as const, hull: SHIPS.colony.hull };
game.ships.push(founder);
assert.match(exportPlan(game, founder.id)!.blocker!, /Reserve the colony ship/);
game.worlds.mars.founded = true;
assert.ok(exportPlan(game, founder.id)!.ready, "A founded Mars releases the colony hull for discretionary pickup runs");
game.worlds.mars.founded = false;
game.ships.pop();
const pad = game.worlds.luna.tiles.find(t => t.building?.type === "pad")!.building!;
pad.progress = 1;
assert.match(exportPlan(game, ship.id)!.blocker!, /finished launch pad/);
pad.progress = 0;
game.credits = DIFF.charter.overdraft;
assert.equal(exportPlan(game, ship.id)!.ready, false, "New fuel still needs available credit");
game.credits = -400;
assert.equal(operationsBrief(game).cash.debtFee, 16);
game.credits = -10;
assert.equal(operationsBrief(game).cash.debtFee, 12);
game.credits = -2000;
assert.equal(operationsBrief(game).cash.debtFee, 60);
game.credits = 1000;
game.earthLaunches = 2;
assert.match(exportPlan(game, ship.id)!.blocker!, /two hulls/);
game.earthLaunches = 0;
game.founding = { shipId: ship.id, world: "luna" };
assert.equal(exportPlan(game, ship.id), null);
game.founding = null;
ship.cargo.food = 2;
assert.equal(exportPlan(game, ship.id), null, "Do not replace a loaded Earth manifest with a trade run");
ship.cargo.food = 0;
ship.loc = "luna";
game.worlds.luna.launches = 1;
assert.match(exportPlan(game, ship.id)!.blocker!, /already fired/);
game.outcome = { kind: "victory" };
assert.equal(exportPlan(game, ship.id), null);
